CREATE TABLE `fe_certificacion` (
	`colmado_id` integer PRIMARY KEY NOT NULL,
	`rnc` text,
	`razon_social` text,
	`nombre_comercial` text,
	`direccion_fiscal` text,
	`tipo_contribuyente` text,
	`correo_fiscal` text,
	`rep_nombre` text,
	`rep_cedula` text,
	`rep_cargo` text,
	`rep_correo` text,
	`cert_entidad` text,
	`cert_estado` text DEFAULT 'no_tiene' NOT NULL,
	`cert_titular` text,
	`cert_vence` text,
	`cert_archivo` text,
	`cert_clave` text,
	`cert_subido_at` integer,
	`pasos` text DEFAULT '{}' NOT NULL,
	`secuencias` text DEFAULT '[]' NOT NULL,
	`autorizado_at` integer,
	`actualizado_por` text,
	`creado_at` integer DEFAULT (cast(unixepoch('subsec') * 1000 as integer)) NOT NULL,
	`actualizado_at` integer DEFAULT (cast(unixepoch('subsec') * 1000 as integer)) NOT NULL,
	FOREIGN KEY (`colmado_id`) REFERENCES `colmados`(`id`) ON UPDATE no action ON DELETE cascade
);
